// Returns the approximate outdoor transplant window for a crop started indoors.
// Adds cold-frame weeks to the indoor sow window to get the planting-out range.
export function getTransplantWindow(crop) {
  if (!crop.weeksInColdFrame || !crop.sowWindowStart || !crop.sowWindowEnd) return null;
  const monthsToAdd = Math.round(crop.weeksInColdFrame / 4.33);
  const start = ((crop.sowWindowStart - 1 + monthsToAdd) % 12) + 1;
  const end   = ((crop.sowWindowEnd   - 1 + monthsToAdd) % 12) + 1;
  return { start, end };
}

export function isSowableInMonth(crop, month) {
  if (crop.perennial) return false;
  const m = month;
  const inPrimary = crop.sowWindowStart && crop.sowWindowEnd
    ? (crop.sowWindowStart <= crop.sowWindowEnd
        ? m >= crop.sowWindowStart && m <= crop.sowWindowEnd
        : m >= crop.sowWindowStart || m <= crop.sowWindowEnd)
    : false;
  const inAlternate = crop.alternateSowStart && crop.alternateSowEnd
    ? (crop.alternateSowStart <= crop.alternateSowEnd
        ? m >= crop.alternateSowStart && m <= crop.alternateSowEnd
        : m >= crop.alternateSowStart || m <= crop.alternateSowEnd)
    : false;
  return inPrimary || inAlternate;
}

export function isHarvestableInMonth(crop, month) {
  const m = month;
  if (!crop.harvestWindowStart || !crop.harvestWindowEnd) return false;
  return crop.harvestWindowStart <= crop.harvestWindowEnd
    ? m >= crop.harvestWindowStart && m <= crop.harvestWindowEnd
    : m >= crop.harvestWindowStart || m <= crop.harvestWindowEnd;
}

